package fusta_pantalon;
import comun.Imbracaminte;
public class MainFustaPantaloni {
    public static void main(String[] args) {
        Imbracaminte articolFaraArg = new Imbracaminte();
        Fusta fustaFaraArg = new Fusta();
        Pantalon pantaloniFaraArg = new Pantalon();
        System.out.println("Constructori fara argumente:");
        System.out.println("Articol: " + articolFaraArg);
        System.out.println("Fusta: " + fustaFaraArg);
        System.out.println("Pantalon: " + pantaloniFaraArg);
        Imbracaminte articol = new Imbracaminte("Levi's", "32", "albastru", "denim", 150.0, 5);
        Fusta fusta = new Fusta("H&M", "S", "negru", "poliester", 90.0, 15, true, true, "mini", "clos");
        Pantalon pantaloni = new Pantalon("Zara", "M", "bej", "bumbac", 200.0, 8, true, true, "cargo", "inalta");
        System.out.println();
        System.out.println("Constructori cu toate argumentele:");
        System.out.println("Articol: " + articol);
        System.out.println("Fusta: " + fusta);
        System.out.println("Pantaloni: " + pantaloni);
        Imbracaminte copieArticol = new Imbracaminte(articol);
        Fusta copieFusta = new Fusta(fusta);
        Pantalon copiePantalon = new Pantalon(pantaloni);
        copieArticol.setBrand("H&M");
        copieFusta.setBrand("Zara");
        copiePantalon.setBrand("Bershka");
        System.out.println();
        System.out.println("Constructori de copiere:");
        System.out.println("Articol original: " + articol);
        System.out.println("Articol copie: " + copieArticol);
        System.out.println("Fusta originala: " + fusta);
        System.out.println("Fusta copie: " + copieFusta);
        System.out.println("Pantaloni originali: " + pantaloni);
        System.out.println("Pantaloni copie: " + copiePantalon);
        articol.setBrand("Wrangler");
        articol.setMarime("34");
        articol.setCuloare("negru");
        articol.setMaterial("bumbac");
        articol.setPret(180.0);
        articol.setStoc(12);
        fusta.setMarime("M");
        fusta.setCuFermoar(false);
        fusta.setCaptusita(false);
        fusta.setLungime("maxi");
        fusta.setTipCroi("evazat");
        pantaloni.setCuloare("negru");
        pantaloni.setCuCurea(false);
        pantaloni.setCuBuzunare(false);
        pantaloni.setModel("blugi");
        pantaloni.setTalie("medie");
        System.out.println();
        System.out.println("Set si get:");
        System.out.println("Articol: " + articol.getBrand() + ", " + articol.getMarime() + ", " + articol.getCuloare() + ", " + articol.getMaterial() + ", " + articol.getPret() + ", " + articol.getStoc());
        System.out.println("Fusta: " + fusta.getMarime() + ", fermoar " + fusta.isCuFermoar() + ", captusita " + fusta.isCaptusita() + ", lungime " + fusta.getLungime() + ", croi " + fusta.getTipCroi());
        System.out.println("Pantaloni: " + pantaloni.getCuloare() + ", curea " + pantaloni.isCuCurea() + ", buzunare " + pantaloni.isCuBuzunare() + ", model " + pantaloni.getModel() + ", talie " + pantaloni.getTalie());
        articol.aplicaReducere(40);
        fusta.aplicaReducere(20);
        pantaloni.aplicaReducere(15);
        System.out.println();
        System.out.println("Dupa reducere:");
        System.out.println("Articol pret: " + articol.getPret());
        System.out.println("Fusta pret: " + fusta.getPret());
        System.out.println("Pantaloni pret: " + pantaloni.getPret());
        System.out.println();
        System.out.println("Disponibilitate:");
        System.out.println("Articol, 15 buc: " + articol.verificaDisponibilitate(15));
        System.out.println("Fusta, 20 buc: " + fusta.verificaDisponibilitate(20));
        System.out.println("Pantaloni, 25 buc: " + pantaloni.verificaDisponibilitate(25));
        System.out.println();
        System.out.println("Dupa modificari:");
        System.out.println(articol);
        System.out.println(fusta);
        System.out.println(pantaloni);
    }
}
